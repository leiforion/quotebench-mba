#!/usr/bin/env python3
"""T07 pass 3 — move Appendix B/G extracts (incl. schema table) before References;
move 4.6 (Voice of the customer) ahead of 4.7 (Root causes).
Usage: python3 scripts/t07c_appendix_move.py [--apply]
"""
import sys
sys.path.insert(0, "scripts")
from doc_editor import get_service, snapshot, DOC_ID, find_text_range, flat_text

apply = "--apply" in sys.argv
svc = get_service(write=apply)

T1 = "Appendix B (extract) \u2014 Section 7 Exhibits\n"
T2 = "Exhibit 7.1. Projected to-be process for a Tier 2 inquiry. Every System-lane time is a simulation output; the bracketed ID names the Appendix A assumption that carries it. The contractor's reply time is the one interval no redesign controls, shown at its measured Section 4 value.\n"
T3 = "Exhibit 7.2. The proposed architecture. Probabilistic components (sand) are bought; deterministic, rules and data components (white) are built; the selection engine partners with the manufacturer's curve APIs. The dashed return path is the flywheel of Exhibit 7.3.\n"
T4 = "Exhibit 7.3. The correction flywheel. Constraint five of 7.1 makes every human intervention a labelled training example; accuracy rises, routing admits more inquiries to assisted and auto-draft paths, and freed capacity concentrates on complex, high-margin work. Projected mechanism; the pilot observes its first turn.\n"
T5 = "Appendix G (extract) \u2014 Canonical RFQ Schema\n"
T6 = "Table G.1. The canonical RFQ schema (simplified). Fields 4\u20138 repeat per hydraulic system on multi-system inquiries. Field 12 is generated by the extraction layer and is the input to the confidence router of 7.7.\n"

CELLS = [
    ["#", "Field", "Type", "Required", "Typical source"],
    ["1", "Contractor & project identity", "text", "Yes", "Email header / body"],
    ["2", "System type (booster, circulation, transfer, chilled water)", "enum", "Yes", "Schedule / spec"],
    ["3", "Number of distinct hydraulic systems", "integer", "Yes", "Schedule / drawings"],
    ["4", "Design flow rate, per system (m\u00b3/h)", "number", "Yes", "Schedule"],
    ["5", "Static head / vertical rise, per system (m)", "number", "Yes", "Riser diagram"],
    ["6", "Pipe run length (m)", "number", "Yes", "Drawings / spec"],
    ["7", "Pipe diameter and material", "number + enum", "Yes", "Spec"],
    ["8", "Fittings summary (bends, valves, strainers)", "structured list", "Yes", "Drawings / default profile"],
    ["9", "Fluid and temperature", "enum + number", "Yes", "Spec"],
    ["10", "Power supply (voltage / phase)", "enum", "Yes", "Spec"],
    ["11", "Required delivery date", "date", "No", "Email body"],
    ["12", "Attachments manifest & per-field confidence", "metadata", "system", "Generated"],
]

VOC_HEAD = "4.6 Voice of the customer\n"
VOC_PARA = "Contractor interviews are in progress at the time of writing (protocol in Appendix D): four to six structured conversations covering what drives supplier choice, how speed weighs against price, and \u2014 because no live system exists to observe \u2014 each contractor's stated reaction to the hypothetical of an automated quote. Preliminary conversations consistently point to response speed and error-free technical submittals as decisive selection factors, which supports the direction of this design; verbatim quotations, including any dissenting views, will be incorporated once transcripts are complete (E, provisional). Stated preferences are the paper's only demand-side evidence, and Section 9.3 treats them accordingly: as an upper bound to be triangulated, not a measurement.\n"


def must_find(doc, needle, label):
    rng, n = find_text_range(doc, needle)
    if rng is None:
        print(f"FAIL: {label} -> {n} matches")
        sys.exit(1)
    return rng


doc = svc.documents().get(documentId=DOC_ID).execute()
print("snapshot:", snapshot(doc))

refs_s, _ = must_find(doc, "References\n", "References heading")
b_s, _ = must_find(doc, T1, "Appendix B head")
_, g6_e = must_find(doc, T6, "Table G.1 caption")
voc_h_s, voc_h_e = must_find(doc, VOC_HEAD, "VoC heading")
voc_p_s, voc_p_e = must_find(doc, VOC_PARA, "VoC paragraph")
rc_s, _ = must_find(doc, "4.7 Root causes\n", "4.7 heading")

print(f"extract block [{b_s},{g6_e}) -> insert at References @{refs_s}")
print(f"VoC block [{voc_h_s},{voc_p_e}) -> insert at 4.7 @{rc_s}")
assert rc_s < voc_h_s < voc_p_e < b_s < g6_e < refs_s, "unexpected document order"
assert voc_p_s - voc_h_e < 5, "VoC head/para not adjacent"

if not apply:
    print("DRY RUN — anchors located, nothing written.")
    sys.exit(0)

# --- batch 1: high-index ops first (extract copy at refs_s), then VoC move ---
reqs = [{"insertText": {"location": {"index": refs_s}, "text": T6}},
        {"insertTable": {"rows": 13, "columns": 5, "location": {"index": refs_s}}}]
for t in [T5, T4, T3, T2, T1]:
    reqs.append({"insertText": {"location": {"index": refs_s}, "text": t}})
reqs.append({"deleteContentRange": {"range": {"startIndex": voc_h_s, "endIndex": voc_p_e}}})
reqs.append({"insertText": {"location": {"index": rc_s}, "text": VOC_PARA}})
reqs.append({"insertText": {"location": {"index": rc_s}, "text": VOC_HEAD}})
svc.documents().batchUpdate(documentId=DOC_ID, body={"requests": reqs}).execute()
print("batch 1 applied (extract copy inserted, VoC moved)")

# --- batch 2: refetch; fix styles, populate table, delete original block ---
doc = svc.documents().get(documentId=DOC_ID).execute()

paras = []
for item in doc["body"]["content"]:
    if "paragraph" in item:
        text = "".join(el.get("textRun", {}).get("content", "")
                       for el in item["paragraph"].get("elements", []))
        paras.append((text, item["startIndex"], item["endIndex"]))

def pick(prefix, which):
    hits = [p for p in paras if p[0].startswith(prefix)]
    assert hits, f"missing paragraph: {prefix[:50]!r}"
    return hits[0] if which == "first" else hits[-1]

reqs2 = []

def style_para(prefix, which, named, bold):
    _, s, e = pick(prefix, which)
    reqs2.append({"updateParagraphStyle": {"range": {"startIndex": s, "endIndex": e},
                  "paragraphStyle": {"namedStyleType": named}, "fields": "namedStyleType"}})
    reqs2.append({"updateTextStyle": {"range": {"startIndex": s, "endIndex": e - 1},
                  "textStyle": {"bold": bold}, "fields": "bold"}})

# destination copies = highest-index occurrences
style_para(T1.rstrip("\n"), "last", "HEADING_2", True)
style_para(T5.rstrip("\n"), "last", "HEADING_2", True)
for cap in (T2, T3, T4, T6):
    style_para(cap[:60], "last", "NORMAL_TEXT", False)
# moved VoC block (original deleted in batch 1, so first occurrence = moved copy)
style_para("4.6 Voice of the customer", "first", "HEADING_2", True)
style_para("Contractor interviews are in progress", "first", "NORMAL_TEXT", False)

# populate the new empty 13x5 table
empty_tables = []
for item in doc["body"]["content"]:
    if "table" in item and item["table"]["rows"] == 13 and item["table"]["columns"] == 5:
        texts = []
        for row in item["table"]["tableRows"]:
            for cell in row["tableCells"]:
                t = ""
                for ce in cell["content"]:
                    if "paragraph" in ce:
                        t += "".join(el.get("textRun", {}).get("content", "")
                                     for el in ce["paragraph"].get("elements", []))
                texts.append(t.strip())
        if all(t == "" for t in texts):
            empty_tables.append(item)
assert len(empty_tables) == 1, f"expected 1 empty 13x5 table, found {len(empty_tables)}"

cell_inserts = []
for r, row in enumerate(empty_tables[0]["table"]["tableRows"]):
    for c, cell in enumerate(row["tableCells"]):
        idx = cell["content"][0]["startIndex"]
        cell_inserts.append((idx, CELLS[r][c], r == 0))
cell_inserts.sort(key=lambda x: -x[0])
for idx, text, bold in cell_inserts:
    reqs2.append({"insertText": {"location": {"index": idx}, "text": text}})
    if bold:
        reqs2.append({"updateTextStyle": {"range": {"startIndex": idx, "endIndex": idx + len(text)},
                      "textStyle": {"bold": True}, "fields": "bold"}})

# delete original extract block (first occurrence, lowest index; executes last)
text_all, idxs = flat_text(doc)
orig_start = idxs[text_all.find(T1)]
orig_end = idxs[text_all.find(T6) + len(T6) - 1] + 1
new_refs_s, _ = must_find(doc, "References\n", "References")
assert orig_start < orig_end < new_refs_s, "original block must precede the new copy"
reqs2.append({"deleteContentRange": {"range": {"startIndex": orig_start, "endIndex": orig_end}}})

svc.documents().batchUpdate(documentId=DOC_ID, body={"requests": reqs2}).execute()
print(f"batch 2 applied: {len(reqs2)} requests (styles, {len(cell_inserts)} cell fills, original deleted)")
